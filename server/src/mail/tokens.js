import { createHmac, timingSafeEqual, randomUUID } from 'node:crypto';
import { env } from '../config/env.js';

/**
 * Self-validating signed tokens, used for unsubscribe links and tracking URLs.
 *
 * The payload travels in the URL and is verified by signature alone, so there
 * is no database lookup on the hot path and - more importantly - no sequential
 * identifier a stranger could increment to unsubscribe or impersonate someone
 * else's contacts.
 */

const SEPARATOR = '.';

function b64url(buffer) {
  return Buffer.from(buffer).toString('base64url');
}

function sign(payloadB64) {
  return createHmac('sha256', env.TOKEN_HMAC_SECRET).update(payloadB64).digest('base64url');
}

export function createToken(payload) {
  const body = b64url(JSON.stringify(payload));
  return `${body}${SEPARATOR}${sign(body)}`;
}

/**
 * Returns the payload, or null if the token is malformed or the signature
 * does not match. Never throws on bad input - these arrive from the open
 * internet.
 */
export function verifyToken(token) {
  if (typeof token !== 'string' || token.length > 4096) return null;

  const index = token.lastIndexOf(SEPARATOR);
  if (index <= 0) return null;

  const body = token.slice(0, index);
  const signature = token.slice(index + 1);

  const expected = Buffer.from(sign(body));
  const received = Buffer.from(signature);
  // Length check first: timingSafeEqual throws on a length mismatch.
  if (expected.length !== received.length) return null;
  if (!timingSafeEqual(expected, received)) return null;

  try {
    return JSON.parse(Buffer.from(body, 'base64url').toString('utf8'));
  } catch {
    return null;
  }
}

// --- Unsubscribe -----------------------------------------------------------

export function createUnsubscribeToken({ contactId, campaignId, email }) {
  return createToken({ t: 'u', c: contactId, k: campaignId ?? null, e: email });
}

export function readUnsubscribeToken(token) {
  const payload = verifyToken(token);
  if (!payload || payload.t !== 'u') return null;
  return { contactId: payload.c, campaignId: payload.k, email: payload.e };
}

// --- Tracking --------------------------------------------------------------

export function createOpenToken({ contactId, campaignId, messageId }) {
  return createToken({ t: 'o', c: contactId, k: campaignId, m: messageId });
}

export function readOpenToken(token) {
  const payload = verifyToken(token);
  if (!payload || payload.t !== 'o') return null;
  return { contactId: payload.c, campaignId: payload.k, messageId: payload.m };
}

/**
 * The destination URL is signed *inside* the token rather than passed as a
 * query parameter. An unsigned redirect parameter is an open redirect, and an
 * open redirect on a sending domain is a fast route to a blocklist.
 */
export function createClickToken({ contactId, campaignId, messageId, url }) {
  return createToken({ t: 'c', c: contactId, k: campaignId, m: messageId, u: url });
}

export function readClickToken(token) {
  const payload = verifyToken(token);
  if (!payload || payload.t !== 'c') return null;
  return {
    contactId: payload.c,
    campaignId: payload.k,
    messageId: payload.m,
    url: payload.u,
  };
}

// --- Message-ID ------------------------------------------------------------

/**
 * Generated by us rather than by the SMTP server, so the value is known
 * before the send and can be stored on the job. Bounce and reply matching
 * both depend on recognising it later.
 */
export function createMessageId(domain) {
  return `<${Date.now().toString(36)}.${randomUUID()}@${domain}>`;
}
